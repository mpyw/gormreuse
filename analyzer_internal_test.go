package gormreuse

import (
	"go/parser"
	"go/token"
	"testing"
)

// TestIsGeneratedFile checks the generated-file decision on the shapes cmd/cgo
// writes (#186). TestAnalyzer covers the same through a real cgo build, but it
// is skipped without a C compiler.
func TestIsGeneratedFile(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name string
		src  string
		want bool
	}{
		{"plain file", "package p\n", false},
		{"generated file", "// Code generated by some tool. DO NOT EDIT.\n\npackage p\n", true},
		{"cgo output of a user file", cgoHeader + "\n\n//line /src/a.go:1:1\n// Package p.\npackage p\n", false},
		{"cgo output of a generated file", cgoHeader + "\n\n//line /src/a.go:1:1\n// Code generated by some tool. DO NOT EDIT.\n\npackage p\n", true},
		{"cgo's own file", "//go:cgo_ldflag \"-g\"\n" + cgoHeader + "\n\npackage p\n", true},
		{"cgo header without a //line directive", cgoHeader + "\n\n// Package p.\npackage p\n", true},
		{"cgo header alone", cgoHeader + "\n\npackage p\n", true},
		{"cgo header with a //line directive after the package clause", cgoHeader + "\n\npackage p\n\n//line /src/a.go:1:1\nvar x int\n", true},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			file, err := parser.ParseFile(token.NewFileSet(), "a.go", tt.src, parser.ParseComments)
			if err != nil {
				t.Fatal(err)
			}
			if got := isGeneratedFile(file); got != tt.want {
				t.Errorf("isGeneratedFile() = %v, want %v", got, tt.want)
			}
		})
	}
}
