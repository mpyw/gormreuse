package internal

import "go/ast"

// CgoHeader is the first comment of every file that cmd/cgo writes.
const CgoHeader = "// Code generated by cmd/cgo; DO NOT EDIT."

// IsCgoOutput reports whether file is a file of cmd/cgo's output: its first
// comment is CgoHeader.
func IsCgoOutput(file *ast.File) bool {
	return len(file.Comments) > 0 && len(file.Comments[0].List) == 1 && file.Comments[0].List[0].Text == CgoHeader
}
